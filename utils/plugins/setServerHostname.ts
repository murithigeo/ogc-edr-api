import type { ExegesisPlugin, ExegesisPluginContext } from "exegesis-express";
import process from "node:process";
const NODE_ENV = process.env.NODE_ENV || "development";

export default function setServerHostname(): ExegesisPlugin {
  return {
    info: {
      name: "set-server-suffix",
    },
    makeExegesisPlugin: () => {
      return {
        postRouting: (ctx: ExegesisPluginContext) => {
          const uri = new URL(`http://${ctx.req.headers.host}`);
          if (NODE_ENV === "production") uri.protocol = "https";
          const url = uri.toString().slice(0, -1);
          ctx.api.serverObject = {
            url,
            description: `${NODE_ENV} server. Autogenerated depending on host`,
          };
          ctx["ectx"]["server"] = url;
        },
      };
    },
  };
}
